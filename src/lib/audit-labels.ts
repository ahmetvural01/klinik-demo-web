/** Kodun sözlükte (tam adıyla) karşılığı var mı? Yoksa ad yedek çeviridir. */
export function hasAuditActionLabel(action: string): boolean {
  return Object.prototype.hasOwnProperty.call(ACTION_LABELS, action);
}

export function getAuditActionLabel(action: string, detail?: string | null): string {
  if (action === "SETTINGS_UPDATE" && /sms/i.test(detail || "")) return "SMS ayarı güncellendi";
  if (hasAuditActionLabel(action)) return ACTION_LABELS[action];

  // Yedek: kod parça parça çevrilir. Sözlükte olmayan (İngilizce) parça
  // Türkçe kurala göre küçültülmez — "ARCHIVE" → "Archıve" çıkıyordu.
  const parts = action
    .split("_")
    .filter(Boolean)
    .map((part) => {
      const known = WORD_LABELS[part];
      return known !== undefined
        ? { text: known, turkish: true }
        : { text: part.charAt(0) + part.slice(1).toLowerCase(), turkish: false };
    })
    .filter((part) => part.text);
  if (parts.length === 0) return action;
  const [first, ...rest] = parts;
  const head = first.turkish ? first.text.charAt(0).toLocaleUpperCase("tr-TR") + first.text.slice(1) : first.text;
  return [head, ...rest.map((part) => part.text)].join(" ");
}

export function getAuditScopeLabel(action: string, detail?: string | null): string {
  if (action === "LOGIN" || action === "LOGOUT" || action.startsWith("PROFILE_") || action.startsWith("PASSWORD_")) return "Oturum";
  if (action.startsWith("PATIENT_") || action.startsWith("DOCUMENT_") || action.startsWith("CONSENT_")) return "Hasta";
  if (action.startsWith("APPOINTMENT_") || action.startsWith("BOOKING_REQUEST_") || action.startsWith("PUBLIC_BOOKING_") || action.startsWith("WAITLIST_") || action.startsWith("DOCTOR_BLOCK_")) return "Randevu";
  if (action.startsWith("EXAM_") || action.startsWith("TREATMENT_") || action.startsWith("PRESCRIPTION_")) return "Tedavi";
  if (action.startsWith("PAYMENT_") || action.startsWith("KASA_") || action.startsWith("GIDER_") || action.startsWith("TAKSIT_") || action.startsWith("FIRMA_") || action.startsWith("PURCHASE_") || action.startsWith("EXPENSE_")) return "Finans";
  if (action.startsWith("LAB_")) return "Laboratuvar";
  if (action.startsWith("STOCK_")) return "Stok";
  if (action.startsWith("SMS_") || (action === "SETTINGS_UPDATE" && /sms/i.test(detail || ""))) return "SMS";
  if (action.startsWith("SETTINGS_") || action.startsWith("POS_") || action.startsWith("PRICE_") || action.startsWith("SMS_TEMPLATE_") || action.startsWith("FOLLOW_UP_TYPES_")) return "Ayarlar";
  if (action.startsWith("CLINIC_TASK_") || action.startsWith("REMINDER_")) return "Görev";
  if (action.startsWith("SUPPORT_")) return "Destek";
  if (action.startsWith("MESSAGE_") || action.startsWith("ANNOUNCEMENT_")) return "İletişim";
  if (action.startsWith("DEV_") || action.startsWith("DEMO_")) return "Sistem";
  return "Genel";
}
